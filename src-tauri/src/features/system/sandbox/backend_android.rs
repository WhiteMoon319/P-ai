#[cfg(target_os = "android")]
const ANDROID_PROOT_EXEC: &str = "libproot_exec.so";
#[cfg(target_os = "android")]
const ANDROID_PROOT_LOADER: &str = "libproot_loader.so";
#[cfg(target_os = "android")]
const ANDROID_PROOT_REQUIRED_LIBS: &[&str] = &["libtalloc.so", "libandroid-shmem.so"];
#[cfg(target_os = "android")]
const ANDROID_PROOT_TALLOC_COMPAT_LIB: &str = "libtalloc.so.2";
#[cfg(target_os = "android")]
const ANDROID_PROOT_WORKSPACE_DIR: &str = "/workspace";
#[cfg(target_os = "android")]
const ANDROID_PROOT_ASSISTANT_SPACE_DIR: &str = "/root/.pai";

#[cfg(target_os = "android")]
fn android_proot_candidate_dirs() -> Vec<std::path::PathBuf> {
    let mut out = Vec::<std::path::PathBuf>::new();
    let mut seen = std::collections::HashSet::<String>::new();
    let mut push = |path: std::path::PathBuf| {
        if !path.is_dir() {
            return;
        }
        let key = path.to_string_lossy().to_string();
        if seen.insert(key) {
            out.push(path);
        }
    };

    if let Ok(paths) = std::env::var("LD_LIBRARY_PATH") {
        for raw in paths.split(':') {
            let trimmed = raw.trim();
            if !trimmed.is_empty() {
                push(std::path::PathBuf::from(trimmed));
            }
        }
    }

    if let Ok(maps) = std::fs::read_to_string("/proc/self/maps") {
        for token in maps.split_whitespace() {
            if !token.ends_with(".so") {
                continue;
            }
            let path = std::path::PathBuf::from(token);
            let Some(file_name) = path.file_name().and_then(|value| value.to_str()) else {
                continue;
            };
            if matches!(file_name, "libeasy_call_ai_lib.so" | "libtauri_app.so") || file_name.starts_with("libeasy_call") {
                if let Some(parent) = path.parent() {
                    push(parent.to_path_buf());
                }
            }
        }
    }

    out
}

#[cfg(target_os = "android")]
fn android_proot_binary_paths() -> Result<(std::path::PathBuf, std::path::PathBuf, Option<std::path::PathBuf>), String> {
    let candidates = android_proot_candidate_dirs();
    for dir in &candidates {
        let proot = dir.join(ANDROID_PROOT_EXEC);
        if proot.is_file() {
            let loader = dir.join(ANDROID_PROOT_LOADER);
            let loader = if loader.is_file() { Some(loader) } else { None };
            return Ok((dir.clone(), proot, loader));
        }
    }
    let searched = candidates
        .iter()
        .map(|path| path.to_string_lossy().to_string())
        .collect::<Vec<_>>()
        .join(", ");
    Err(format!(
        "Android Linux 执行层缺失：未找到 {ANDROID_PROOT_EXEC}。请把合法来源的 proot native libs 放入 src-tauri/android/jniLibs/<abi>/ 后重新打包。已搜索：{}",
        if searched.is_empty() { "无候选 nativeLibraryDir" } else { searched.as_str() }
    ))
}

#[cfg(target_os = "android")]
fn android_proot_current_group_ids() -> Vec<u64> {
    let Ok(status) = std::fs::read_to_string("/proc/self/status") else {
        return Vec::new();
    };
    let Some(groups) = status.lines().find(|line| line.starts_with("Groups:")) else {
        return Vec::new();
    };
    groups
        .trim_start_matches("Groups:")
        .split_whitespace()
        .filter_map(|item| item.parse::<u64>().ok())
        .collect()
}

#[cfg(target_os = "android")]
fn android_proot_write_if_missing(path: &std::path::Path, content: &str) -> Result<(), String> {
    if path.is_file()
        && std::fs::read_to_string(path)
            .map(|text| !text.trim().is_empty())
            .unwrap_or(false)
    {
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|err| format!("创建 Android rootfs 配置目录失败 ({}): {err}", parent.display()))?;
    }
    std::fs::write(path, content)
        .map_err(|err| format!("写入 Android rootfs 配置失败 ({}): {err}", path.display()))
}

#[cfg(target_os = "android")]
fn android_proot_patch_resolv_conf(etc_dir: &std::path::Path) -> Result<(), String> {
    let path = etc_dir.join("resolv.conf");
    let should_write = match std::fs::symlink_metadata(&path) {
        Ok(metadata) if metadata.file_type().is_symlink() => true,
        Ok(metadata) if !metadata.is_file() => true,
        Ok(_) => std::fs::read_to_string(&path)
            .map(|text| {
                !text.lines().any(|line| {
                    let line = line.trim_start();
                    let Some(server) = line.strip_prefix("nameserver ") else {
                        return false;
                    };
                    let server = server.trim();
                    !matches!(server, "" | "127.0.0.1" | "127.0.0.53" | "::1")
                })
            })
            .unwrap_or(true),
        Err(_) => true,
    };
    if !should_write {
        return Ok(());
    }
    let _ = std::fs::remove_file(&path);
    std::fs::write(
        &path,
        "# Generated by P-AI Android workspace.\nnameserver 1.1.1.1\nnameserver 8.8.8.8\nnameserver 223.5.5.5\noptions edns0 trust-ad\n",
    )
    .map_err(|err| format!("写入 Android rootfs DNS 配置失败 ({}): {err}", path.display()))
}

#[cfg(target_os = "android")]
fn android_proot_patch_group_file(etc_dir: &std::path::Path) -> Result<(), String> {
    let path = etc_dir.join("group");
    if !path.exists() {
        android_proot_write_if_missing(&path, "root:x:0:\n")?;
    }
    let mut text = std::fs::read_to_string(&path).unwrap_or_default();
    let existing_ids = text
        .lines()
        .filter_map(|line| line.split(':').nth(2)?.parse::<u64>().ok())
        .collect::<std::collections::HashSet<_>>();
    let mut additions = Vec::<String>::new();
    for group_id in android_proot_current_group_ids() {
        if group_id > 0 && !existing_ids.contains(&group_id) {
            additions.push(format!("android_gid_{group_id}:x:{group_id}:"));
        }
    }
    if additions.is_empty() {
        return Ok(());
    }
    if !text.ends_with('\n') {
        text.push('\n');
    }
    for line in additions {
        text.push_str(&line);
        text.push('\n');
    }
    std::fs::write(&path, text)
        .map_err(|err| format!("写入 Android rootfs group 配置失败 ({}): {err}", path.display()))
}

