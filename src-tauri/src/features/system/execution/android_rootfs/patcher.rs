use super::*;

pub(crate) fn android_proot_current_group_ids() -> Vec<u64> {
    let Ok(status) = std::fs::read_to_string("/proc/self/status") else {
        return Vec::new();
    };
    let Some(groups) = status.lines().find(|line| line.starts_with("Groups:")) else {
        return Vec::new();
    };
    groups
        .trim_start_matches("Groups:")
        .split_whitespace()
        .filter_map(|item| item.parse::<u64>().ok())
        .collect()
}

pub(crate) fn android_proot_write_if_missing(path: &std::path::Path, content: &str) -> Result<(), String> {
    if path.is_file()
        && std::fs::read_to_string(path)
            .map(|text| !text.trim().is_empty())
            .unwrap_or(false)
    {
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|err| format!("创建 Android rootfs 配置目录失败 ({}): {err}", parent.display()))?;
    }
    std::fs::write(path, content)
        .map_err(|err| format!("写入 Android rootfs 配置失败 ({}): {err}", path.display()))
}

pub(crate) fn android_proot_patch_resolv_conf(etc_dir: &std::path::Path) -> Result<(), String> {
    let path = etc_dir.join("resolv.conf");
    let should_write = match std::fs::symlink_metadata(&path) {
        Ok(metadata) if metadata.file_type().is_symlink() => true,
        Ok(metadata) if !metadata.is_file() => true,
        Ok(_) => std::fs::read_to_string(&path)
            .map(|text| {
                !text.lines().any(|line| {
                    let line = line.trim_start();
                    let Some(server) = line.strip_prefix("nameserver ") else {
                        return false;
                    };
                    let server = server.trim();
                    !matches!(server, "" | "127.0.0.1" | "127.0.0.53" | "::1")
                })
            })
            .unwrap_or(true),
        Err(_) => true,
    };
    if !should_write {
        return Ok(());
    }
    let _ = std::fs::remove_file(&path);
    std::fs::write(
        &path,
        "# Generated by P-AI Android workspace.\nnameserver 1.1.1.1\nnameserver 8.8.8.8\nnameserver 223.5.5.5\noptions edns0 trust-ad\n",
    )
    .map_err(|err| format!("写入 Android rootfs DNS 配置失败 ({}): {err}", path.display()))
}

pub(crate) fn android_proot_patch_group_file(etc_dir: &std::path::Path) -> Result<(), String> {
    let path = etc_dir.join("group");
    if !path.exists() {
        android_proot_write_if_missing(&path, "root:x:0:\n")?;
    }
    let mut text = std::fs::read_to_string(&path).unwrap_or_default();
    let existing_ids = text
        .lines()
        .filter_map(|line| line.split(':').nth(2)?.parse::<u64>().ok())
        .collect::<std::collections::HashSet<_>>();
    let mut additions = Vec::<String>::new();
    for group_id in android_proot_current_group_ids() {
        if group_id > 0 && !existing_ids.contains(&group_id) {
            additions.push(format!("android_gid_{group_id}:x:{group_id}:"));
        }
    }
    if additions.is_empty() {
        return Ok(());
    }
    if !text.ends_with('\n') {
        text.push('\n');
    }
    for line in additions {
        text.push_str(&line);
        text.push('\n');
    }
    std::fs::write(&path, text)
        .map_err(|err| format!("写入 Android rootfs group 配置失败 ({}): {err}", path.display()))
}

pub(crate) fn android_proot_set_path_mode(path: &std::path::Path, mode: u32) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode));
    }
    #[cfg(not(unix))]
    {
        let _ = path;
        let _ = mode;
    }
}

pub(crate) fn android_proot_set_dir_mode(path: &std::path::Path, mode: u32) {
    android_proot_set_path_mode(path, mode);
}

